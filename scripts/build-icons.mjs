// Copies the few Lucide icons the app uses into public/js/icons.js (so no icon requests at runtime).
import { readFileSync, writeFileSync } from "node:fs";

const NAMES = [
  "flame", "school", "graduation-cap", "sun", "moon", "monitor", "plus", "trash-2", "check", "x", "lightbulb", "eye",
  "arrow-right", "arrow-left", "rotate-ccw", "target", "trophy", "layers", "calculator", "clipboard-check",
  "message-circle", "pen-line", "send-horizontal", "upload", "file-text", "book-open", "chevron-down",
  "notebook-pen", "notebook-text", "copy", "play", "shuffle", "sparkles", "log-out", "users", "link",
  "circle-help", "circle-dashed", "triangle-alert", "circle-check", "info", "pencil", "calendar", "chart-column",
  "clock", "log-in", "circle-dot", "bot", "user-round",
];

const out = {};
for (const name of NAMES) {
  const svg = readFileSync(`node_modules/lucide-static/icons/${name}.svg`, "utf8");
  out[name] = svg.replace(/^[\s\S]*?<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "").replace(/\s+/g, " ").trim();
}
writeFileSync(
  "public/js/icons.js",
  `// Generated by scripts/build-icons.mjs from Lucide (ISC license). Do not edit by hand.\nexport const ICONS = ${JSON.stringify(out, null, 1)};\n`
);
console.log(`wrote ${NAMES.length} icons`);
